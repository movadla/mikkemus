import { pairKey } from "./teamNames";

/**
 * A team's kit — the shirt it plays in.
 *
 * Worked out from the team's members and nothing else, so the same two people are in the same
 * shirt on every device and in every match, with nothing stored and nothing to set up: putting
 * Per and Ola together again brings their shirt back by itself, because it is the same sum.
 * Every team has two, a first kit and an away kit; when two teams in one match would wear
 * colours too alike to tell apart, the second of them plays in its away kit.
 *
 * These are drawn shirts, not pictures: nothing here is generated by an image model. A team
 * card with a real image would replace the drawing at the one place it is rendered
 * (components/TeamKit.tsx) without anything in this file changing.
 */

export type KitPattern = "solid" | "hoops" | "stripes" | "sash" | "halves" | "chevron";

export type Kit = {
  primary: string;
  secondary: string;
  /** Collar and cuffs. */
  trim: string;
  pattern: KitPattern;
};

/** Colour pairs chosen to be unmistakable at 24 px and to read on the app's dark green. */
const PALETTE: { primary: string; secondary: string; trim: string }[] = [
  { primary: "#d8392b", secondary: "#f4f0e8", trim: "#f4f0e8" }, // red / cream
  { primary: "#2f6fd1", secondary: "#f4f0e8", trim: "#f4f0e8" }, // blue / cream
  { primary: "#e8c13a", secondary: "#1d2a4a", trim: "#1d2a4a" }, // yellow / navy
  { primary: "#f4f0e8", secondary: "#c4432e", trim: "#c4432e" }, // white / red
  { primary: "#7a3fb0", secondary: "#f0d76a", trim: "#f0d76a" }, // purple / gold
  { primary: "#e8772e", secondary: "#1b1b1b", trim: "#1b1b1b" }, // orange / black
  { primary: "#1f9d8a", secondary: "#f4f0e8", trim: "#f4f0e8" }, // teal / cream
  { primary: "#26262b", secondary: "#e8c13a", trim: "#e8c13a" }, // black / yellow
  { primary: "#d94f9a", secondary: "#f4f0e8", trim: "#f4f0e8" }, // pink / cream
  { primary: "#3f8f3a", secondary: "#f4f0e8", trim: "#f4f0e8" }, // green / cream
  { primary: "#8b1e3f", secondary: "#e8d9a8", trim: "#e8d9a8" }, // claret / sand
  { primary: "#5db7e8", secondary: "#1d2a4a", trim: "#1d2a4a" }, // sky / navy
];

const PATTERNS: KitPattern[] = ["hoops", "stripes", "solid", "sash", "halves", "chevron"];

/** FNV-1a — small, stable, and spreads two similar names far apart. */
function hash(text: string): number {
  let h = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) {
    h ^= text.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h >>> 0;
}

export function firstKit(members: string[]): Kit {
  const h = hash(pairKey(members) || "ingen");
  const colours = PALETTE[h % PALETTE.length];
  return { ...colours, pattern: PATTERNS[(h >>> 8) % PATTERNS.length] };
}

/** A different shirt for the same team: the colours swapped over and a different pattern, so it
 *  reads as the same club in other colours rather than as another club. */
export function awayKit(members: string[]): Kit {
  const first = firstKit(members);
  const h = hash(pairKey(members) || "ingen");
  const colours = PALETTE[(h + 5) % PALETTE.length];
  const flipped = h % 2 === 0;
  return {
    primary: flipped ? colours.secondary : colours.primary,
    secondary: flipped ? colours.primary : colours.secondary,
    trim: colours.trim,
    pattern: PATTERNS[(PATTERNS.indexOf(first.pattern) + 2) % PATTERNS.length],
  };
}

function rgb(hex: string): [number, number, number] {
  const n = parseInt(hex.slice(1), 16);
  return [(n >> 16) & 255, (n >> 8) & 255, n & 255];
}

/** How far apart two shirts look, by their main colour — plain distance in RGB, which is crude
 *  but enough to catch red against red and to leave red against blue alone. */
export function kitDistance(a: Kit, b: Kit): number {
  const [r1, g1, b1] = rgb(a.primary);
  const [r2, g2, b2] = rgb(b.primary);
  return Math.sqrt((r1 - r2) ** 2 + (g1 - g2) ** 2 + (b1 - b2) ** 2);
}

/** Below this, two shirts are too alike to tell apart across a room. */
export const CLASH_DISTANCE = 110;

export type TeamForKit = { name: string; members: string[] };

/**
 * The shirt every team in a match plays in. Teams are taken in order and each is checked against
 * those already placed: the first to clash gets its away kit, so the order they were set up in
 * decides who changes. If the away kit clashes as well (rare), the team keeps whichever of its
 * two is further from the nearest shirt already taken.
 */
export function assignKits(teams: TeamForKit[]): Record<string, { kit: Kit; away: boolean }> {
  const placed: Kit[] = [];
  const result: Record<string, { kit: Kit; away: boolean }> = {};
  for (const team of teams) {
    const home = firstKit(team.members);
    const away = awayKit(team.members);
    const nearest = (kit: Kit) => (placed.length === 0 ? Infinity : Math.min(...placed.map((p) => kitDistance(kit, p))));
    const useAway = nearest(home) < CLASH_DISTANCE && nearest(away) > nearest(home);
    const chosen = useAway ? away : home;
    placed.push(chosen);
    result[team.name] = { kit: chosen, away: useAway };
  }
  return result;
}
